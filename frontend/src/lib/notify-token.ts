import { keepBox } from '@/lib/keep-box';
/* 서버를 부르는 자리의 생김새. 타입만 가져오므로 웹 파일이 앱 묶음에
   끌려 들어가지 않습니다 — {@code lib/notify.ts} 도 같은 길로 받습니다. */
import type { ApiClient } from '@/lib/notify.web';

/**
 * 「이 기기에서 알림 받기」를 기억해 두는 자리.
 *
 * <h3>모듈 변수 한 줄이었습니다</h3>
 *
 * <p>켠 열쇠를 {@code let token} 에 들고 있었습니다. 그래서 앱을 닫고 다시
 * 열면 그 줄이 비고, 폰이 허락해 둔 상태여도 스위치가 <b>꺼진 채로</b>
 * 보였습니다. 서버에는 등록이 멀쩡히 남아 있는데 화면만 아니라고 한
 * 것입니다 — 그러면 다시 누르게 되고, 누르면 서버가 「켰어요」 알림을 한 번
 * 더 보냅니다.
 *
 * <p>앱 쪽은 더 자주 일어났습니다. 앱은 웹을 띄우는 껍데기라 앱을 켤 때마다
 * <b>웹이 처음부터 다시 뜹니다.</b> 모듈 변수는 그때마다 빕니다.
 *
 * <h3>기기에 남기는 것만으로는 모자랍니다</h3>
 *
 * <p>남겨 둔 열쇠가 <b>서버에서 사라져 있을 수 있습니다.</b> 중계 서버가
 * 404·410 으로 답하면 서버는 그 자리를 지웁니다(PushService) — 앱을 지웠다
 * 다시 깔았을 때가 그렇습니다. 그러면 기기에만 남은 열쇠로 「켜져 있어요」를
 * 말하게 되고, 그 말은 <b>틀린 말</b>입니다. 스위치가 말하는 것은 내 기기의
 * 사정이 아니라 <b>서버가 나를 알고 있는가</b>이기 때문입니다.
 *
 * <p>그래서 둘을 같이 봅니다 — 기기에 남은 열쇠가 있는지, 그리고 서버가
 * 그것을 들고 있는지.
 *
 * <h3>켤 때마다 다시 등록하지 않습니다</h3>
 *
 * <p>앱을 열 때마다 그냥 다시 등록해 버리는 길도 있습니다. 그러면 기억할
 * 것이 없습니다. 다만 서버가 등록을 받을 때마다 「알림을 켰어요」를 한 번
 * 보냅니다(PushController 의 hello) — 앱을 열 때마다 알림이 오는 앱이
 * 됩니다. 묻는 것이 보내는 것보다 쌉니다.
 *
 * <h3>사람마다가 아니라 기기마다입니다</h3>
 *
 * <p>Expo 열쇠는 <b>이 설치</b>의 것이라 누가 로그인했는지와 무관합니다.
 * 그래서 사람 번호를 열쇠에 안 넣습니다({@code lib/keep} 과 다릅니다).
 * 「이 열쇠가 지금 로그인한 사람의 것인가」는 서버가 답합니다.
 */

/** 기기에 남길 자리. {@code lib/keep} 과 같은 접두사 규칙입니다. */
const KEY = 'fit.push.token';

/** 켜 둔 열쇠를 기기에 남깁니다. */
export function remember(token: string): void {
  try {
    keepBox()?.setItem(KEY, token);
  } catch {
    /* 사파리 사생활 보호 모드처럼 있는데 못 쓰는 데가 있습니다. 못 남겨도
       알림은 켜집니다 — 앱을 다시 열었을 때 스위치가 꺼져 보일 뿐입니다. */
  }
}

/** 남겨 둔 열쇠. 없으면 null. */
export function remembered(): string | null {
  try {
    return keepBox()?.getItem(KEY) ?? null;
  } catch {
    return null;
  }
}

/** 이 기기에서는 그만 받기로 했습니다. */
export function forget(): void {
  try {
    keepBox()?.removeItem(KEY);
  } catch {
    /* 못 지워도 아래 {@link stillOn} 이 서버에 물어 「아니오」를 받습니다. */
  }
}

/**
 * 남겨 둔 열쇠를 서버가 아직 들고 있는지.
 *
 * <h3>물어볼 수 없을 때는 아는 대로 답합니다</h3>
 *
 * <p>망이 안 터지면 알 길이 없습니다. 그때 「꺼짐」으로 답하면 멀쩡히 켜
 * 둔 사람에게 꺼진 스위치를 보여 주는 것이고, 그 사람은 다시 누릅니다.
 * 마지막으로 알던 것을 그대로 말합니다 — 켜 두었다는 것입니다.
 *
 * <h3>「아니오」 를 받아도 남겨 둔 것은 안 지웁니다</h3>
 *
 * <p>한 폰을 둘이 쓰면 「아니오」가 나올 수 있습니다 — 내가 켜 둔 폰에
 * 동행자가 로그인하면 서버는 그 사람에게 등록이 없다고 답합니다. 그때
 * 열쇠를 지워 버리면 내가 다시 로그인했을 때도 꺼진 것으로 보입니다.
 * 열쇠는 기기의 것이고, 켜 둔 사람이 누구인지는 서버만 압니다.
 *
 * @param token 기기에 남겨 둔 열쇠
 */
export async function stillOn(api: ApiClient, token: string): Promise<boolean> {
  try {
    /*
      열쇠를 함께 보냅니다.

      <p>지금 서버의 /api/push/state 는 <b>이 사람이 어디서든</b> 켜 두었는지를
      답합니다(PushService.on 이 사람 번호로 셉니다). 스위치가 말하는 것은
      「이 기기에서」라 그것보다 넓습니다 — 폰에서 켜 둔 사람이 노트북
      브라우저에서도 켜진 스위치를 봅니다.

      <p>그래도 「아니오」는 확실합니다. 등록이 하나도 없으면 이 기기의 것도
      없습니다. 좁히는 것은 서버가 이 값을 읽어 주면 그때 됩니다 — 그때까지
      모르는 칸은 모르는 쪽이 아니라 <b>켜진 쪽</b>으로 둡니다. 꺼진 것을
      켜진 것으로 보이는 쪽이, 켜 둔 것을 꺼진 것으로 보이는 쪽보다 낫습니다
      (후자는 다시 누르게 하고, 다시 누르면 알림이 한 번 더 옵니다).
    */
    const got = await api.get<{ on: boolean }>(
      `/api/push/state?endpoint=${encodeURIComponent(token)}`,
    );
    return got.on;
  } catch {
    return true;
  }
}
