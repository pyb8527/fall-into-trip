/**
 * 지도·장소 검색이 주고받는 모양.
 *
 * 웹과 앱 구현이 각각 따로 있어서(.web.tsx / .tsx), 타입은 어느 쪽도 아닌
 * 이 파일에 둡니다. 그래야 화면 코드가 어느 구현을 보든 같은 타입을 씁니다.
 */

export type MapPlace = {
  id: string;
  name: string;
  lat: number;
  lng: number;
  /** 몇째 날인지. 같은 날끼리 선으로 잇습니다. */
  dayIndex: number;
  /** 그날 안에서 몇 번째인지. 핀에 적습니다. */
  order: number;
  /**
   * 핀 안에 그릴 그림.
   *
   * <p>같은 모양 핀이 스무 개 꽂혀 있으면 지도는 그냥 점의 무리입니다.
   * 라멘집인지 온천인지가 핀만 보고 읽히면, 다 짜 놓은 지도를 한 장으로
   * 찍었을 때 그것이 곧 여행의 요약이 됩니다.
   *
   * <p>비어 있으면 번호만 찍힌 핀을 그립니다.
   */
  emoji?: string;
  color: string;
  /** 공항처럼 멀리 떨어진 곳. 화면을 맞출 때 뺍니다. */
  fit: boolean;
  radius: number | null;
  /** 전체화면에서 핀을 눌렀을 때 바텀시트에 보여 줄 것들. */
  detail: {
    time: string | null;
    cat: string | null;
    cost: string | null;
    note: string | null;
    sub: string | null;
    dayLabel: string;
    visited: boolean;
  };
};

/** 지도에 얹는 사람과 임시 핀. 장소 핀과 생김새를 달리해 헷갈리지 않게 합니다. */
export type MapMate = {
  id: string;
  name: string;
  /**
   * 지도에 찍을 것. 고른 동물의 이모지, 안 골랐으면 이름 첫 글자.
   *
   * <p>이름 첫 글자만 찍고 있었습니다. "지영" 과 "지훈" 이 지도에서 똑같이
   * "지" 하나로 보여, 누가 어디 있는지 보라고 켠 것인데 정작 누구인지가 안
   * 보였습니다.
   */
  face: string;
  lat: number;
  lng: number;
};

export type MapNote = {
  id: string;
  label: string | null;
  lat: number;
  lng: number;
};

export type TripMapProps = {
  /** 지금 켜 둔 동행자들. */
  mates?: MapMate[];
  /** 잠깐 꽂아 둔 핀들. */
  notes?: MapNote[];
  /** 지금 내가 있는 자리. 켰을 때만 옵니다. */
  here?: { lat: number; lng: number; accuracy: number } | null;
  /** 내 자리에 찍을 것. 동행자와 같은 방식으로 나도 그립니다. */
  myFace?: string;
  /** 있으면 점선 대신 이것을 그립니다. */
  routes?: RouteLine[];
  /**
   * 길을 다시 묻고 있는 중인지.
   *
   * <h3>왜 이것을 지도가 알아야 하는가</h3>
   *
   * <p>날짜를 바꾸면 장소는 곧바로 바뀌고 길은 다시 물어야 합니다. 그 틈에
   * 지도는 <b>길이 없는 것</b>과 <b>아직 안 온 것</b>을 구별하지 못해서,
   * 못 받은 구간이라 여기고 점선을 그렸습니다. 그리고 몇백 밀리초 뒤 실선이
   * 오면 점선이 실선으로 바뀌었습니다.
   *
   * <p>한 번 깜빡이는 정도가 아니라 <b>틀린 말을 하는 것</b>입니다. 점선은
   * "이 구간은 길을 못 찾았다" 는 뜻인데 찾는 중에 그렇게 말합니다.
   *
   * <p>묻는 동안에는 아무것도 안 그리고 "길 찾는 중" 이라고 적습니다.
   */
  routesPending?: boolean;
  /**
   * 길 위를 지나가는 것 하나.
   *
   * <h3>왜 지도는 셈을 안 하는가</h3>
   *
   * <p>어디쯤인지, 어느 쪽을 보는지, 얼마나 떠 있는지는 <b>부르는 쪽이
   * 셉니다.</b> 지도는 받은 자리에 그리기만 합니다.
   *
   * <p>지도가 둘이기 때문입니다(웹·앱). 셈을 지도 안에 두면 같은 계산을
   * 두 벌 쓰게 되고, 한쪽만 고치는 날 둘이 다르게 납니다. 그릴 줄만 둘로
   * 두고 셈은 하나로 둡니다.
   *
   * @param heading 어느 쪽을 보고 있는지. 북쪽이 0, 시계 방향으로 도 단위
   * @param lift    얼마나 떠 있는지. 0 이면 내려앉은 것, 1 이면 한창 나는 중.
   *                자리에 설 때 작아지고 날 때 커져서 <b>뜨고 내리는</b>
   *                것처럼 보입니다
   */
  traveler?: { lat: number; lng: number; heading: number; lift: number; color: string } | null;
  places: MapPlace[];
  activeId: string | null;
  onSelect: (id: string) => void;
  height?: number;
  /**
   * 지도 위에 얹는 단추들(내 위치·전체화면)을 보일지.
   *
   * <p>지도가 화면 전체를 채우는 일정 화면에서는 "전체화면" 이 뜻이 없고,
   * 그 자리는 위쪽 막대와 겹칩니다. 그럴 때 끕니다.
   */
  chrome?: boolean;
  /** 지도가 화면을 꽉 채울 때. 모서리를 둥글리지 않습니다. */
  bleed?: boolean;
  /**
   * 장소끼리 선으로 이을지.
   *
   * <p>일정에서는 이어야 합니다 — 순서가 곧 동선입니다. 보석함처럼 순서가
   * 없는 곳에서는 이으면 안 됩니다. 담아 둔 차례가 무슨 길인 것처럼 보여,
   * 있지도 않은 동선을 그려 놓게 됩니다.
   */
  link?: boolean;
  /**
   * 날짜별로 걸러 볼 수 있게 할지.
   *
   * <h3>왜 지도가 이것을 갖는가</h3>
   *
   * <p>전체화면은 이 컴포넌트 안에 있습니다. 밖에서 걸러 넘기면 작은 지도만
   * 걸러지고 <b>전체화면으로 펴는 순간 다시 전부</b>가 됩니다 — 정작 날짜별로
   * 보고 싶은 때는 크게 펼쳤을 때입니다.
   *
   * <p>일정 화면처럼 이미 제 날짜 띠를 가진 곳에서는 켜지 않습니다. 띠가
   * 둘이 되면 어느 것이 듣는지 알 수 없습니다.
   */
  dayFilter?: boolean;
  /**
   * 아래쪽이 몇 픽셀 가려져 있는지.
   *
   * <p>일정 판이 지도 위로 올라와 아래를 덮습니다. 이것을 모르면 고른 장소를
   * 화면 한가운데로 보내는데, 그 가운데가 판에 덮여 있어 정작 안 보입니다.
   * 덮인 만큼 위로 밀어 올려 <b>보이는 곳의 가운데</b>에 놓습니다.
   */
  bottomInset?: number;
  /**
   * 내 위치로 옮겨 달라는 신호.
   *
   * <p>값이 <b>바뀔 때마다</b> 지도가 내 자리로 갑니다. 무엇으로 바뀌는지는
   * 상관없고 달라지기만 하면 됩니다 — 같은 자리를 두 번 눌러도 두 번 다
   * 움직여야 하므로, 자리를 넘기는 대신 "눌렀다" 는 것만 넘깁니다.
   */
  goHereAt?: number;
  /**
   * 전부 한 화면에 담아 달라는 신호.
   *
   * <p>값이 바뀔 때마다 지도가 뒤로 물러나 넣어 둔 곳을 모두 보여 줍니다.
   * 다시 보기가 끝났을 때처럼 "이만큼 돌았다" 를 한눈에 보여 줘야 할 때
   * 씁니다.
   */
  fitAt?: number;
  /**
   * 고른 곳을 따라갈 때 <b>이웃한 곳까지 함께</b> 보이게 할지.
   *
   * <h3>다시보기가 먼 곳에서 끊겨 보이던 까닭</h3>
   *
   * <p>고른 곳이 바뀌면 지도가 그 자리로 옮겨 가면서 배율 16까지 당깁니다.
   * 들여다보는 데는 맞지만, 다시보기처럼 <b>1.1초마다 다음 곳으로 넘어가는</b>
   * 자리에서는 문제가 됩니다 — 구글 지도는 목표가 화면 밖이면 부드럽게 가지
   * 않고 순간이동하고, 바짝 당겨 둔 탓에 먼 다음 곳은 늘 화면 밖입니다.
   * 게다가 옮겨 가는 도중에 다음 옮김이 시작되어 앞엣것이 잘립니다.
   *
   * <p>이것을 켜면 당기는 대신 <b>앞뒤 곳이 같이 들어오게</b> 맞춥니다.
   * 동선이 화면에 남은 채 눈길만 옮겨 가고, 먼 구간에서는 저절로 물러납니다.
   */
  follow?: boolean;
  /**
   * 핀 모양.
   *
   * <p>기본은 일정용입니다 — 그림이 있으면 그림, 없으면 번호. 보석함처럼
   * 순서도 갈래도 앞세울 것이 없는 자리에서는 <code>star</code> 로 둡니다.
   * 전부 같은 동그라미에 별 하나라, 어디에 얼마나 담겼는지만 보입니다.
   */
  shape?: 'default' | 'star';
  /**
   * 이 자리로 옮겨 달라는 신호.
   *
   * <p><code>at</code> 이 바뀔 때마다 지도가 그 좌표로 갑니다. 일정에 없는
   * 것(꽂아 둔 깃발 같은)을 가리킬 때 씁니다 — 그런 것에는 고를 id 가
   * 없습니다.
   */
  panTo?: { lat: number; lng: number; at: number } | null;
};

/** 검색으로 찾은 장소. */
export type Found = {
  name: string;
  address: string;
  lat: number;
  lng: number;
  /** 구글이 아는 번호. 나중에 영업시간을 물어볼 때 씁니다. */
  placeId: string | null;
  /** 구글이 알려 준 갈래로 서버가 미리 찍어 둔 핀 그림. 없을 수도 있습니다. */
  icon?: string | null;
};

export type PlaceSearchProps = {
  onPick: (found: Found) => void;
  /** 지금 서 있는 자리. 있으면 찾은 곳이 여기서 얼마나 먼지 적습니다. */
  here?: { lat: number; lng: number } | null;
};

/**
 * 지도에 그릴 실제 이동 경로.
 *
 * <p>없으면 지도는 장소끼리 점선으로 잇습니다. 그건 "이 순서로 간다" 는 뜻일
 * 뿐 실제로 지나는 길이 아닙니다.
 */
export type RouteLine = {
  id: string;
  color: string;
  points: { lat: number; lng: number }[];
};
