import type { Maybe } from '@/api/types';
import { OurPhoto } from '@/components/our-photo';
import { TripMark } from '@/components/trip-mark';

/**
 * 여행 줄 맨 앞의 48 칸 — 사진이 있으면 사진, 없으면 표식.
 *
 * <h3>왜 둘을 겹치지 않는가</h3>
 *
 * <p>사진을 깔고 그 위에 표식을 작은 배지로 얹는 쪽을 먼저 그려 봤습니다.
 * 48 에서는 안 됩니다. 배지는 18~20 이 한계인데 {@link TripMark} 가 지닌
 * 것은 <b>24 짜리 이모지</b>와 <b>48×48 을 12% 로 깐 색</b>이고, 둘 다 그
 * 48 칸을 다 써야 읽힙니다 — 이모지는 줄 제목(16)보다 작아지는 순간 「이름
 * 앞에 붙은 글자 하나」가 되고, 12% 는 깔 면이 없어지면 아예 안 보여서 색을
 * 꽉 채우는 쪽으로 되돌아가야 합니다. 그것이 바로 표식이 12% 로 내려온
 * 까닭이었습니다.
 *
 * <h3>그리고 셈이 어긋납니다</h3>
 *
 * <p>겹치기에서 배지가 뜻을 갖는 것은 <b>색이나 이모지를 정한 여행</b>이고,
 * 새로 드는 구글 호출을 치르는 것은 <b>사진이 없는 여행</b>입니다. 그 두
 * 묶음은 서로 아무 상관이 없습니다 — 아무것도 안 정한 여행이 가장 흔한데,
 * 그 줄은 배지로 얻는 것이 하나도 없으면서 동선 그림 값을 새로 냅니다.
 * <b>얻는 것이 없는 자리에 값을 치르게 됩니다.</b>
 *
 * <p>이렇게 가르면 호출이 <b>하나도</b> 안 늡니다. 쓰는 것은 서버가 목록에
 * 이미 실어 보낸 사진 번호뿐이고({@code firstPhotoId}), 없으면 여태 그랬듯
 * 표식이 섭니다. 사진이 없는 여행은 오늘과 똑같이 공짜입니다.
 *
 * <h3>{@link TripThumb} 을 안 씁니다</h3>
 *
 * <p>그 부품은 표지 → 첫 사진 → <b>동선 그림</b> 세 칸으로 떨어지는 것이
 * 제 일입니다. 마지막 칸이 바로 여기서 안 내려는 구글 호출입니다. 「지도는
 * 빼라」는 깃발을 달아 주는 쪽도 생각했는데, 그러면 세 칸으로 떨어지는 것이
 * 일인 부품이 어떤 자리에서는 안 떨어지는 것이 됩니다 — 그 부품의 doc 이
 * 설명하는 규칙이 더 이상 참이 아니게 됩니다. 사진 한 장을 그리는 일은
 * {@link OurPhoto} 가 이미 하므로, 여기서는 그것을 바로 씁니다.
 *
 * <h3>부품을 따로 두는 까닭</h3>
 *
 * <p>내 여행과 모임 상세가 <b>같은 칸</b>을 세워야 합니다. 같은 여행이 화면을
 * 옮기면 다른 것으로 보이지 않게 하려고 표식을 넣은 것이라, 그 둘이 어긋나면
 * 표식을 넣은 까닭이 없어집니다. 두 화면에 같은 삼항식을 두 벌 적어 두면
 * 한쪽만 고치는 날이 옵니다.
 */
export function TripSlot({
  theme,
  emoji,
  firstPhotoId,
}: {
  theme: Maybe<string>;
  emoji: Maybe<string>;
  /** 그 여행의 첫 사진. 없으면 표식이 섭니다. */
  firstPhotoId: Maybe<string>;
}) {
  if (firstPhotoId) {
    /*
      48×48 로 못박습니다.

      <p>{@link OurPhoto} 는 폭을 안 주면 {@code '100%'} 입니다 — 줄에 그냥
      놓으면 줄 폭을 다 가져가고 옆의 제목이 0 까지 밀립니다. 틀의 모서리
      ({@code Radius.r3})와 받아 오는 동안의 바탕({@code Colors.fill})이
      {@link TripMark} 의 타일과 같은 값이라, 사진이 선 줄과 표식이 선 줄이
      나란히 있어도 칸의 생김새는 하나입니다.
    */
    return <OurPhoto id={firstPhotoId} width={48} height={48} />;
  }

  /* 색도 이모지도 안 정했으면 이쪽이 빈 48 칸을 냅니다. 줄을 맞추는 일이
     거기 있으므로 여기서 {@code null} 로 떨어뜨리면 안 됩니다 — 그러면
     사진도 표식도 없는 줄만 제목이 왼쪽으로 밀립니다. */
  return <TripMark theme={theme} emoji={emoji} />;
}
