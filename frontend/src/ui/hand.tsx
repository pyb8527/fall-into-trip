import { useFonts } from 'expo-font';

/**
 * 이 앱의 글자.
 *
 * <h3>왜 글꼴을 바꿨는가</h3>
 *
 * <p>화면이 딱딱하다는 말을 들었습니다. 회색 바닥에 흰 판, 그림자 없음,
 * 위계는 굵기로만 — 토스에서 가져온 얼개입니다. 그런데 토스가 그렇게 서는
 * 것은 그 앱이 <b>돈</b>을 다루기 때문입니다. 잔액 앞에서 화려하면 안 됩니다.
 *
 * <p>FIT 은 여행입니다. 기다리고, 떠나고, 돌아와 들춰 보는 것. 카피는 이미
 * 그렇게 쓰여 있는데("어디로 떠나 볼까요?", "지금 그 길 위", "이대로 갑니다")
 * 글자가 은행 화면의 목소리로 그것을 읽고 있었습니다.
 *
 * <p>이서윤체입니다. 흥국생명이 무료로 푼 손글씨체로, 또박또박 쓴 펜글씨라
 * 귀엽지도 유치하지도 않습니다. 제목에만 쓸까 하다가 <b>전부</b> 이것으로
 * 갑니다 — 두 글꼴이 섞이면 어느 것이 이 앱의 목소리인지 흐려집니다.
 *
 * <h3>그래서 바뀐 것</h3>
 *
 * <p>1종입니다. 굵기 파일이 하나뿐이라 없는 굵기는 기기가 <b>합성</b>하는데,
 * 획이 가늘고 굽은 글꼴에서는 그것이 서로 붙어 먹으로 번진 것처럼 됩니다.
 * 그래서 {@code Weight} 를 전부 400 으로 눕히고, 위계는 크기와 색이 지게
 * 했습니다. 자간도 풀었습니다 — 프리텐다드에 맞춰 조여 둔 값이라 손글씨에서는
 * 획이 닿습니다({@code Type}).
 *
 * <h3>웹과 앱이 같은 파일을 씁니다</h3>
 *
 * <p>프리텐다드는 웹만 쓰기 때문에 CSS 로 불러옵니다(global.css). 이쪽은
 * 양쪽에 다 있어야 해서 expo-font 로 갑니다 — 앱에서는 번들에 실리고
 * 웹에서는 FontFace 로 붙습니다. 파일은 {@code assets/fonts} 하나뿐입니다.
 */
export function HandFont({ children }: { children: React.ReactNode }) {
  /* eslint-disable-next-line @typescript-eslint/no-var-requires */
  const [loaded, failed] = useFonts({ LeeSeoyun: require('@/assets/fonts/LeeSeoyun.ttf') });

  /*
    받을 때까지 아무것도 안 그립니다.

    <h3>왜 기다리는가</h3>

    <p>안드로이드는 <b>등록되지 않은 글꼴 이름</b>을 받으면 그것을 찾다가
    글자를 아예 안 그릴 수 있습니다. 그런데 이제 앱의 모든 글자가 이 이름을
    달고 있어서, 도착 전에 그리면 화면이 통째로 빈 채로 뜰 수 있습니다.

    <p>기다리는 값은 쌉니다. 앱에서는 번들에 실려 있어 디스크에서 읽는
    것뿐이고, 웹에서는 뒤에 프리텐다드가 받쳐 주고 있어 늦어도 글자는
    보입니다.

    <p>못 받아도 넘어갑니다. 글꼴 하나 때문에 앱이 안 열리는 것보다, 기기
    글꼴로라도 보이는 편이 낫습니다.
  */
  if (!loaded && !failed) {
    return null;
  }
  return <>{children}</>;
}
