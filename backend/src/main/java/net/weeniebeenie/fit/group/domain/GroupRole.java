package net.weeniebeenie.fit.group.domain;

/**
 * 모임 안에서의 자리.
 *
 * <p>둘뿐입니다. 운영진·부방장 같은 것은 안 둡니다 — 스무 명짜리 모임에
 * 결재선이 필요하지 않습니다.
 *
 * <p>여행에 있던 「보기만」(VIEWER)도 안 옮겨 왔습니다. 모임에 구경꾼을 두는
 * 것은 앞뒤가 안 맞습니다 — 보여 주기만 하려면 여행기를 올려 링크를 주면
 * 되고, 그쪽이 그 일을 하는 자리입니다.
 */
public enum GroupRole {
    /** 만든 사람. 이름을 고치고, 내보내고, 지웁니다. */
    OWNER,
    /** 그 밖의 모두. 여행을 만들고 고치고, 글을 올리고, 사람을 부릅니다. */
    MEMBER
}
