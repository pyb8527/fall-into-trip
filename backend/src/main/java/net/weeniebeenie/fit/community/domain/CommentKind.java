package net.weeniebeenie.fit.community.domain;

/**
 * 이 댓글이 무엇에 달린 것인지.
 *
 * <h3>표 하나를 둘이 나눠 씁니다</h3>
 *
 * <p>피드 글 댓글을 새 표로 파는 길도 있었습니다. 안 그런 이유는 신고·숨김·
 * 운영 화면이 <b>이미 이 표를 보고 있기</b> 때문입니다. 표를 또 파면 그 셋을
 * 두 벌로 만들어야 하고, 그러면 한쪽만 고치는 날이 옵니다.
 *
 * <p>값이 있습니다 — {@code post_id} 한 칸이 두 표를 가리키게 되어
 * <b>외래키를 못 겁니다.</b> 지금까지 DB 가 대신 해 주던 일(글이 지워지면
 * 댓글도 간다)이 코드로 넘어옵니다. 글을 지우는 자리가 둘이고, 거기서
 * 빼먹으면 지운 글의 댓글이 영영 남습니다.
 */
public enum CommentKind {

    /** 둘러보기에 올린 여행기에 달린 것. */
    JOURNAL,

    /** 모임이나 내 피드의 글에 달린 것. */
    FEED
}
