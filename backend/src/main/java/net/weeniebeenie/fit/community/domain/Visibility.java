package net.weeniebeenie.fit.community.domain;

/**
 * 글이 어디까지 보이는지.
 *
 * <h3>왜 셋인가</h3>
 *
 * <p>지금까지는 올리면 무조건 둘러보기에 떴습니다. 그런데 여행기를 쓰는
 * 까닭은 셋으로 갈립니다.
 *
 * <ul>
 *   <li><b>남에게 보여 주려고</b> — 둘러보기에 뜹니다
 *   <li><b>같이 간 사람에게만 보여 주려고</b> — 주소를 아는 사람만
 *   <li><b>나중에 내가 다시 보려고</b> — 나만
 * </ul>
 *
 * <p>셋째가 없으면 "다녀온 것을 정리해 두기" 가 곧 "남에게 내놓기" 가 됩니다.
 * 그러면 대충 쓰거나 아예 안 씁니다.
 *
 * <h3>가운데가 왜 따로 있는가</h3>
 *
 * <p>둘만 두면 "우리끼리 보는 여행기" 를 둘러보기에 올려야 합니다. 그건
 * 남에게는 맥락 없는 글이고, 쓰는 사람에게는 남이 보는 자리에 사사로운
 * 말을 적는 일입니다.
 */
public enum Visibility {

    /** 둘러보기에 뜹니다. 지금까지의 동작이라 기본값입니다. */
    LISTED,

    /**
     * 주소를 아는 사람만.
     *
     * <p>목록·검색·인기에 안 잡힙니다. 번호는 아홉 바이트 난수라 찍어서 맞힐
     * 수 있는 값이 아닙니다 — 다만 주소를 받은 사람이 다시 남에게 보내는 것은
     * 막지 못합니다. 그것까지 막아야 하면 PRIVATE 입니다.
     */
    LINK,

    /** 나만. 글쓴이 말고는 열 수 없습니다. */
    PRIVATE
}
