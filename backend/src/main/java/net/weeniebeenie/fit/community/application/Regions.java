    /** 아무 네모에도 안 걸린 곳. 목록의 마지막 칸이기도 합니다. */
    private static final String ELSEWHERE = "그 밖";

    /**
     * 네모 하나 — 남쪽·북쪽 위도와 서쪽·동쪽 경도.
     *
     * @param region 이 안이면 꼽을 지역. {@link #ALL} 에 있는 값이어야 합니다
     */
    private record Box(String region, double south, double north, double west, double east) {

        boolean has(double lat, double lng) {
            return lat >= south && lat <= north && lng >= west && lng <= east;
        }
    }

