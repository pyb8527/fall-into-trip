package net.weeniebeenie.fit.feed.domain;

/**
 * 피드 글을 누가 볼 수 있는지.
 *
 * <h3>왜 셋인가</h3>
 *
 * <p>지금까지는 올린 자리가 곧 공개 범위였습니다 — 모임에 올리면 그 모임
 * 사람이 보고, 내 피드에 쓰면 나만 봤습니다. 그래서 고를 것이 없는 대신
 * <b>올린 자리를 바꾸는 것 말고는 길이 없었습니다</b>. 모임 사람에게 보여
 * 주려던 사진을 나중에 혼자 간직하려면 글을 지우고 다시 써야 했습니다.
 *
 * <ul>
 *   <li><b>{@link #EVERYONE}</b> — 번호를 아는 사람이면 봅니다
 *   <li><b>{@link #MATES}</b> — 내 모임 사람만
 *   <li><b>{@link #ONLY_ME}</b> — 나만
 * </ul>
 *
 * <h3>여행기의 {@code Visibility} 를 나눠 쓰지 않습니다</h3>
 *
 * <p>{@code community.domain.Visibility} 는 {@code LISTED}/{@code LINK}/
 * {@code PRIVATE} 셋입니다. 겹치는 것이 둘뿐입니다.
 *
 * <p>{@code LINK}(주소 아는 사람만)는 피드에 <b>뜻이 없습니다</b>. 그 갈래가
 * 하는 일은 "둘러보기 목록에서는 빠지고 주소로는 열린다" 인데, 피드에는 애초에
 * 남이 뒤지는 목록이 없습니다 — 모임 피드와 제 피드와 여행 앨범이 전부고,
 * 셋 다 볼 사람이 이미 정해져 있습니다. 넣어 두면 골라도 아무 일이 안 일어나는
 * 값이 하나 생깁니다.
 *
 * <p>거꾸로 {@link #MATES}(내 모임 사람만)는 여행기에 없습니다. 여행기는 한
 * 사람이 내놓는 글이라 "내 모임" 이라는 울타리를 가질 일이 없습니다. 값 하나를
 * 영영 안 쓰고 값 하나를 새로 붙이는 enum 을 나눠 쓰는 것은 <b>같은 것을 쓰는
 * 게 아니라 이름만 같은 것</b>이 됩니다. 피드의 것을 따로 둡니다.
 */
public enum Audience {

    /**
     * 모두.
     *
     * <p>번호를 아는 사람이면 봅니다. 모임에 올린 글이라도 그렇습니다 —
     * 모임 울타리를 그대로 두면 모임 글에서는 이 갈래가 {@link #MATES} 와
     * 똑같아져, 골라도 아무 일이 안 일어납니다.
     *
     * <p>목록이 넓어지는 것은 아닙니다. 남의 피드는 여전히 <b>나와 함께 속한
     * 모임</b>의 글만 늘어놓습니다({@code PostRepository.ofAuthorIn}) — 이
     * 갈래는 "뒤지면 나온다" 가 아니라 "건네받은 번호로 열린다" 입니다.
     */
    EVERYONE,

    /**
     * 내 모임 사람만.
     *
     * <p>글 하나만 봐서는 못 가립니다 — 보는 사람과 글쓴이가 <b>같은 모임에
     * 있나</b>를 물어야 합니다. 올린 자리에 따라 묻는 것이 갈립니다.
     *
     * <pre>
     *   모임에 올린 글   → 그 모임 사람
     *   내 피드에 쓴 글  → 나와 모임을 함께 쓰는 사람
     * </pre>
     *
     * <p>모임에 올린 글을 "나와 모임을 함께 쓰는 사람" 으로 넓히지 않습니다.
     * 그러면 A 모임에 올린 글이 B 모임 사람에게 보입니다 — 올린 사람이 고른
     * 자리는 A 였습니다.
     */
    MATES,

    /**
     * 나만.
     *
     * <p>글쓴이 말고는 열 수 없습니다. 모임에 올린 글이라도 그렇습니다.
     *
     * <p>못 보는 사람에게는 <b>없다</b>고 답합니다 — 여행기 쪽과 같은
     * 약속입니다({@code PostService.read}).
     */
    ONLY_ME
}
