package net.weeniebeenie.fit.trip.domain;

/**
 * 사진이 하는 일.
 *
 * <p>같은 장소에 붙는 사진이라도 둘은 전혀 다른 것입니다. 한 칸에 담아 두면
 * 남의 여행기에 예매 QR 이 실립니다.
 */
public enum PhotoKind {

    /**
     * 다녀와서 남긴 것.
     *
     * <p>여행기에 실립니다. 올릴 때 사본 안으로 따라 들어갑니다.
     */
    RECORD,

    /**
     * 가기 전에 챙겨 둔 것 — 메뉴판, 예매 화면, 가는 길 지도.
     *
     * <p>여행기에는 <b>안 실립니다.</b> 이건 다니면서 보려고 넣어 둔 것이지
     * 남에게 보여 주려고 넣은 것이 아닙니다.
     */
    REFERENCE
}
