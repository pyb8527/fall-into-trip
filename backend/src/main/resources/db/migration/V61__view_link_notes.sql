--
-- 보기 링크는 날짜 · 장소 · 시각 · 메모를 냅니다. 그런데 장소 메모에는
-- 예약 번호, 현관 비번처럼 동행끼리만 볼 것이 적힐 때가 있습니다
-- (docs/2026-10/plan-view-memo.md §1). 칸마다 공개 범위를 두는 대신,
-- 링크 하나에 메모를 보일지 끌지 스위치 하나만 둡니다 — 조사가 바란
-- 「나만 · 동행 · 바깥」 삼단은 버렸습니다(같은 문서 §3.1).
--
-- 기본은 켜짐입니다. 이미 보낸 링크가 받은 사람 손에서 어느 날 갑자기
-- 달라지면 안 되고, 지금까지 쭉 메모가 나가고 있었습니다 — 이 칸이
-- 생긴다고 그 사실이 바뀌면 안 됩니다.
--
-- 되돌리려면: ALTER TABLE trips DROP COLUMN view_notes; (다음 번호로)
