-- 캘린더 구독 — 폰 캘린더가 로그인 없이 읽어 가는 주소의 열쇠.
--
-- 사람마다 하나입니다
--
--   여행마다 두면 여행을 만들 때마다 구독을 또 걸어야 합니다. 사람마다
--   하나를 두고, 그 사람이 볼 수 있는 여행 전부를 담습니다. 「못 가요」라고
--   한 여행은 뺍니다(V43).
--
-- 해시로만 둡니다
--
--   이 값 하나로 로그인 없이 일정이 읽힙니다. 데이터베이스가 새도 주소를
--   되살릴 수 없게 GroupInvite 와 같이 SHA-256 만 남깁니다. 원문은 만들 때
--   한 번만 화면에 보여 줍니다.
--
-- 새로 만들면 옛 주소가 죽습니다
--
--   주소가 샌 것 같으면 새로 만들면 됩니다. 모르는 주소와 죽은 주소는 똑같이
--   404 입니다.
--
-- 담지 않는 것
--
--   가계부, 위치, 메모, 안내판. 날짜와 장소 이름, 시각만 담습니다.

ALTER TABLE users ADD COLUMN cal_token_hash VARCHAR(64);

CREATE UNIQUE INDEX ux_users_cal_token ON users (cal_token_hash) WHERE cal_token_hash IS NOT NULL;
