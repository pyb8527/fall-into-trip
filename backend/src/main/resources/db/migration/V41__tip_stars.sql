-- 한 줄에 별 한 칸.
--
-- V37 에서 장소의 `stars` · `review` 를 걷으면서 적어 두었습니다 — "별점은
-- 버리는 것이 아니라 옮겨 갑니다. place_tips 가 이미 구글 장소 번호에 달려
-- 있어서, 거기 별 한 칸을 더하면 남의 일정에서도 보이고 쌓입니다(4단계)."
-- 그 4단계입니다.
--
-- 왜 장소가 아니라 한 줄에 다는가
--
--   걷어 낸 `places.stars` 는 <b>내 일정의 그 장소</b>에 달려 있었습니다.
--   같은 가게를 넣어 둔 남의 일정에서는 안 보였고, 그래서 열 사람이 다녀가도
--   별점이 열 군데에 하나씩 흩어졌습니다. 쌓이는 곳이 없으면 평균도 없습니다.
--
--   `place_tips` 는 구글 장소 번호(`place_id VARCHAR(255)`)에 답니다. 같은
--   가게면 누구의 일정에서 보든 같은 줄입니다. 별을 여기 달면 모입니다.
--
-- 왜 글과 따로 두지 않는가
--
--   「별점표」를 따로 만들면 한 사람이 같은 가게에 별 따로 · 한 줄 따로 남길
--   수 있고, 그 둘을 한 화면에 묶어 보여 주려면 매번 맞춰 붙여야 합니다.
--   한 줄에 별이 붙은 것으로 둡니다 — G-11 화면이 그리는 모양 그대로입니다
--   (얼굴 · 이름 · 별 · 한 줄).

-- 1~5. 비워 둘 수 있습니다 — 「별 다섯 + 한 줄, 둘 중 하나만 써도 됩니다」
-- (docs/groups/screens.md G-11). 별만 주고 싶은 사람도 있고 할 말만 있는
-- 사람도 있습니다.
ALTER TABLE place_tips
    ADD COLUMN stars SMALLINT CHECK (stars BETWEEN 1 AND 5);

-- 한 장소의 평균을 셈할 때 감춰진 글은 빼야 합니다. 신고로 내린 글의 별이
-- 평균에 남아 있으면 내린 뜻이 없습니다.
--
-- 이미 ix_tips_place (place_id, hidden, created_at DESC) 가 있어서 그 둘로
-- 거르는 것은 빠릅니다. 별이 있는 줄만 세는 부분 인덱스를 하나 더 둡니다 —
-- 별을 안 준 한 줄이 대부분일 테고, 평균은 그것들을 넘겨야 합니다.
CREATE INDEX ix_tips_stars ON place_tips (place_id)
    WHERE stars IS NOT NULL AND hidden = FALSE;
