--  ---------------------------------------------------------------------------
--  처음에는 JSONB 로 두었습니다. 편명·시각·터미널을 따로 담을 생각이었던 것
--  같은데, 그대로 두 해가 지나도록 화면이 한 번도 쓰지 않았습니다. 쓰려고
--  보니 이유가 있었습니다 — "OZ112 09:20 인천 T1" 을 넣으려면 먼저 그것을
--  무슨 모양으로 쪼갤지 정해야 하고, 그 모양은 항공·기차·버스·페리마다
--  다릅니다.
--
--  사람이 적고 사람이 읽는 한 줄입니다. 지도에 찍지도, 계산에 쓰지도
--  않습니다. 쪼개 둘 이유가 없습니다.
--
--  담긴 것이 없어 옮길 것도 없지만, 혹시 있으면 JSON 을 풀어 글줄로 넣습니다.
-- ============================================================================

ALTER TABLE days
    ALTER COLUMN flight TYPE VARCHAR(200)
        USING CASE
            WHEN flight IS NULL THEN NULL
            -- 따옴표만 두른 글줄이면 벗겨서, 아니면 통째로 적어 둡니다.
            WHEN jsonb_typeof(flight) = 'string' THEN flight #>> '{}'
            ELSE left(flight::text, 200)
        END;
