-- 고친 자취 — 댓글과 장소 리뷰.
--
-- 「내가 남긴 것」을 모아 보는 자리가 생기면서 거기서 바로 고칠 수 있게
-- 되었습니다(docs/feedback-2026-10-02.md 5번). 지우기는 이미 있었고 고치기만
-- 없었습니다.
--
-- 고칠 수 있다는 것은 **쓴 뒤에 말을 바꿀 수 있다**는 뜻입니다. 댓글은 위아래가
-- 서로 받는 글이라, 아무 자취 없이 바뀌면 아래의 대답이 위의 물음에 안 맞는
-- 일이 생깁니다 — 「그 집 말고 옆집」에 「저도 그렇게 생각해요」가 달린 뒤
-- 위를 「여기가 제일 낫다」로 고치면, 동의한 사람이 반대한 것처럼 됩니다.
-- 장소 리뷰도 같습니다. 별 하나에 「최악」이라고 적어 둔 것을 나중에 지우고
-- 다듬어도, 그 사이에 그것을 읽고 안 간 사람이 있습니다.
--
-- 그래서 고친 때를 남깁니다. 비어 있으면 **한 번도 안 고친 것**입니다 —
-- created_at 과 같은 값을 넣어 두는 쪽은 안 씁니다. 그러면 「고침」을 띄울지
-- 말지를 두 값이 같은지로 가려야 하고, 밀리초 하나가 어긋나는 날 처음 쓴 글이
-- 고친 글로 보입니다.
--
-- 고친 내용은 안 남깁니다. 판마다 줄을 쌓으면 글 하나가 표 하나가 되고, 그것을
-- 보여 줄 화면도 없습니다. 지금 필요한 것은 「바뀐 적이 있다」 하나입니다.

ALTER TABLE post_comments ADD COLUMN edited_at TIMESTAMPTZ;
ALTER TABLE place_tips ADD COLUMN edited_at TIMESTAMPTZ;

-- 내가 남긴 댓글을 최근 것부터.
--
-- 리뷰 쪽에는 이미 있습니다(V10 의 ix_tips_user). 댓글 쪽은 지금까지 **글에서
-- 아래로** 만 읽었으므로 ix_comments_post (post_id, kind, hidden, created_at)
-- 하나로 됐습니다. 「내가 남긴 것」은 거꾸로 **사람에서** 읽는 첫 질의라, 이
-- 색인이 없으면 댓글 표를 통째로 훑고 정렬합니다.
--
-- hidden 은 안 넣습니다. 감춰진 댓글은 신고가 세 번 쌓인 것뿐이라 거의 없고,
-- 색인 칸을 하나 늘리면 댓글을 쓸 때마다 그 값을 치릅니다.
CREATE INDEX ix_comments_user ON post_comments (user_id, created_at DESC);
