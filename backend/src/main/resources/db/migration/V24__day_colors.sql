-- 날짜 색을 새 여덟 색으로 옮깁니다.
--
-- 강조색을 코랄로 들이면서 첫째 날의 #f04452 가 그것과 거의 같은 색이
-- 되었습니다. 날짜는 이름표일 뿐인데 그 하나만 "지금 눌러야 할 것" 처럼
-- 보입니다. 보라 둘(#7c5cff·#845ef7)과 초록 둘(#00a98f·#12b886)은 애초에
-- 서로 구별이 안 되던 것이라 이참에 같이 갈랐습니다.
--
-- 색은 날짜를 만들 때 한 번 저장됩니다. 그래서 배열만 바꾸면 앞으로 만드는
-- 여행에만 듣고, 이미 있는 여행은 옛 색을 그대로 들고 있습니다. 여기서
-- 옮겨 줍니다.
--
-- 사람이 손으로 골라 둔 색은 안 건드립니다 — 아래 여덟 값과 정확히 같은
-- 것만 바꿉니다. 그것이 곧 "기본값 그대로인 날" 이라는 뜻입니다.
UPDATE days SET color = CASE color
    WHEN '#f04452' THEN '#3182f6'   -- 붉은색 → 파랑. 강조색에 자리를 내줍니다.
    WHEN '#e07800' THEN '#e8590c'   -- 앰버 → 주황
    WHEN '#7c5cff' THEN '#0ca678'   -- 보라 → 초록
    WHEN '#00a98f' THEN '#9c36b5'   -- 청록 → 자주
    WHEN '#3182f6' THEN '#0b7285'   -- 파랑 → 짙은 청록
    WHEN '#e8590c' THEN '#8b5a2b'   -- 주황 → 갈색
    WHEN '#12b886' THEN '#5c7f1a'   -- 초록 → 올리브
    WHEN '#845ef7' THEN '#7b2d4e'   -- 보라(둘째) → 와인
    ELSE color
END
WHERE color IN (
    '#f04452', '#e07800', '#7c5cff', '#00a98f',
    '#3182f6', '#e8590c', '#12b886', '#845ef7'
);
