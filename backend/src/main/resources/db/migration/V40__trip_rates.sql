-- 환전했을 때의 환율을 적어 두는 자리.
--
-- V16 에서 통화를 붙이면서 "통화가 다르면 서로 상계할 수 없다" 고 정했습니다.
-- 엔으로 받을 돈과 원으로 낼 돈은 더해지지 않으니 정산을 통화마다 따로 냈고,
-- 그래서 가계부 합계가 "￥54,200" 과 "￥80,000" 두 줄로 섭니다.
--
-- 그 둘을 더해 "대충 얼마 썼나" 를 보려면 환율이 있어야 합니다. 그런데 어디서
-- 받아 온 환율(중간값)은 <b>지갑에서 나간 돈과 다릅니다</b> — 공항 환전은
-- 특히 그렇고, 카드는 비자·마스터의 환율에 수수료가 또 붙습니다. 받아 온
-- 숫자로 셈하면 늘 조금씩 틀린 값을 보여 주게 됩니다.
--
-- 그래서 받아 오지 않고 <b>적어 둡니다.</b> 환전할 때 영수증에 찍힌 값이
-- 그 사람이 실제로 겪은 환율입니다.
--
-- 여행마다, 통화마다 하나입니다. 지출마다 두지 않는 까닭은 간단합니다 —
-- 환전은 여행 한 번에 한두 번 하는 일이고, 밥값마다 환율을 적게 하면 아무도
-- 안 적습니다.

CREATE TABLE trip_rates (
    trip_id  VARCHAR(16)  NOT NULL REFERENCES trips (id) ON DELETE CASCADE,
    -- ISO 4217 세 글자. CHAR 로 두면 뒤를 공백으로 채워 'JPY ' 와 'JPY' 가
    -- 달라집니다(V16 에서 같은 이유로 VARCHAR 를 썼습니다)
    currency VARCHAR(3)   NOT NULL,

    -- 이 통화 1 단위가 몇 원인지. 1엔 = 9.17원이면 9.170000 입니다.
    --
    -- 원화를 기준으로 둡니다. 쓰는 사람이 한국에 있고, Currencies.clean 도
    -- 빈 값을 원화로 봅니다.
    --
    -- NUMERIC 입니다. 돈을 셈하는 값에 double 을 쓰면 0.1 을 못 적어서
    -- 합계가 한두 원씩 어긋납니다. 18,6 은 베트남 동(1동 = 0.052원)처럼
    -- 아주 작은 값과 쿠웨이트 디나르(1디나르 = 4,400원)처럼 큰 값을 함께
    -- 담습니다
    rate     NUMERIC(18, 6) NOT NULL CHECK (rate > 0),

    -- 언제 적었는지. 환율이 많이 달라졌을 때 "그때 적어 둔 값이 지금도
    -- 맞나" 를 물어볼 수 있게 남깁니다
    noted_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- 한 여행에서 한 통화에 하나입니다. 두 번 환전해 환율이 달랐다면 나중에
    -- 적은 것이 이깁니다 — 둘을 따로 들고 어느 지출이 어느 환전에서 나온
    -- 돈인지 가리는 일은, 그것을 적을 사람이 없습니다
    PRIMARY KEY (trip_id, currency)
);

-- 원화를 적어 둘 일은 없습니다. 1원은 1원입니다 — 줄을 두면 화면이 "원 ―
-- 1원 = __원" 을 묻게 됩니다
ALTER TABLE trip_rates ADD CONSTRAINT ck_trip_rates_not_krw CHECK (currency <> 'KRW');
