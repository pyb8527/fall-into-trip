-- ============================================================================
--  지출에 통화를 붙입니다.
--  ---------------------------------------------------------------------------
--  처음 만들 때는 엔 단위 정수로만 두었습니다. 그런데 이 앱은 오사카만 가는
--  것이 아닙니다 — 대만·홍콩·방콕도 가고, 같은 여행 안에서 공항 환전 수수료는
--  원화, 밥값은 엔화인 일도 흔합니다.
--
--  통화가 다르면 서로 상계할 수 없습니다. 엔으로 받을 돈과 원으로 낼 돈은
--  더해지지 않습니다. 그래서 정산은 통화마다 따로 냅니다.
--
--  amount 는 그 통화의 가장 작은 단위입니다 — 엔·원은 1, 달러는 1센트.
--  자릿수는 JDK 가 통화별로 알고 있어(java.util.Currency) 우리가 표를 들고
--  있지 않습니다.
--
--  이미 쌓인 것이 있으면 엔으로 봅니다. 지금까지 그 뜻이었습니다.
-- ============================================================================

ALTER TABLE expenses
    -- CHAR 로 두면 뒤를 공백으로 채웁니다. 'JPY ' 와 'JPY' 가 달라져
    -- 통화별로 가를 때 어긋납니다.
    ADD COLUMN currency VARCHAR(3) NOT NULL DEFAULT 'JPY';

-- 정산은 여행별로 통화를 나눠 셉니다.
CREATE INDEX ix_expenses_trip_currency ON expenses (trip_id, currency);
