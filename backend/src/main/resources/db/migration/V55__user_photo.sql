-- 사람 프로필의 얼굴 사진.
--
-- 지금까지 얼굴은 이모지 하나였습니다(users.mark — V17). 그 칸은 원래
-- **지도에서 사람을 가리키는 그림**으로 들어왔습니다. 동행자 위치를 이름 첫
-- 글자로 찍으니 "지영"이든 "지훈"이든 지도에 "지" 하나만 떠서, 누가 어디
-- 있는지 보라고 켠 것인데 정작 누구인지가 안 보였습니다. 그래서 토끼와 곰을
-- 골랐습니다 — 아무리 작게 그려도 서로 다릅니다.
--
-- 그런데 마이페이지가 그 값을 **프로필 얼굴로도** 쓰고 있습니다. 한 칸이 두
-- 일을 하고 있고, 그 둘은 바라는 것이 다릅니다. 지도의 핀은 16픽셀에 들어가야
-- 하므로 그림이 단순해야 하고, 프로필 얼굴은 그 사람이어야 합니다.
--
-- 사진을 받습니다. 표식은 **그대로 둡니다** — 지도에서 하던 일이 그 칸의 원래
-- 일이고, 사진을 지도 핀으로 쓰는 것은 다른 이야기입니다(16픽셀로 줄인 얼굴
-- 사진은 누구인지 안 보입니다). 사진이 있으면 프로필에서만 사진이 섭니다.

-- ------------------------------------------------------------------ 어느 칸
--
-- users 에 칸 하나를 답니다. 표를 따로 두지 않습니다 — 한 사람에 한 장이고,
-- 프로필을 읽을 때 늘 함께 필요합니다. 표를 가르면 마이페이지를 열 때마다
-- 조인 하나가 늘고, 얻는 것이 없습니다.
--
-- cover_photo_id 들과 같은 모양입니다(V33 의 trip_posts, V38 의 groups).
ALTER TABLE users ADD COLUMN photo_id VARCHAR(16) REFERENCES photos (id) ON DELETE SET NULL;

-- ------------------------------------------------------------------ 지울 때
--
-- 사진이 사라지면 **얼굴만** 비웁니다(SET NULL). 사람은 그대로 남습니다.
--
-- 적는 것이 당연해 보이지만 반대쪽이 조용히 무섭습니다. CASCADE 로 두면
-- 사진 한 장을 지우는 일이 **그 사람의 계정을 지우는 일**이 됩니다 — 사진은
-- 사람이 보관함에서 한 장씩 지우는 것이고, 그 줄에 계정이 딸려 갈 수 있다는
-- 것을 지우는 사람도 우리도 모릅니다. 거꾸로 photos.owner_id 가 CASCADE 인
-- 것은 맞습니다(V31): 사람이 사라지면 그 사람의 사진도 사라져야 합니다.
--
-- 그래서 두 방향이 다릅니다. 사람 → 사진은 CASCADE, 사진 → 얼굴은 SET NULL.

-- ------------------------------------------------------------------ 색인
--
-- 색인은 안 답니다.
--
-- 이 칸으로 찾는 질의가 없습니다. 늘 사람 번호로 users 한 줄을 집어 온 뒤에
-- 거기 적힌 사진을 쓰는 쪽이라, 거를 일이 없습니다.
--
-- 외래키 때문에 다는 길은 있습니다. 사진을 지울 때 PostgreSQL 이 이 칸을
-- 훑어야 하니까요. 그런데 훑는 것이 users 이고 그것은 이 서비스에서 가장 작은
-- 표입니다 — 사진 한 장을 지울 때 한 번 하는 일에, 사람을 고칠 때마다 색인
-- 값을 치를 이유가 없습니다. V54 가 posts.place_id 에 색인을 안 단 것과 같은
-- 셈입니다.

-- ------------------------------------------------------------------ 몫
--
-- 얼굴 사진도 photos 에 들어가므로 **사람당 1000장**을 함께 먹습니다
-- (PhotoService 의 MAX_PER_USER). 예외를 두려면 사진에 갈래를 달고 세는 자리를
-- 가려야 하는데, 천 장에서 한 장(0.1%)을 위해 그것을 하지 않습니다.
--
-- 대신 **쌓이지 않게** 합니다. 얼굴은 바꾸는 것이라 그대로 두면 바꾼 횟수만큼
-- 묵은 장이 남습니다 — 스무 번 바꾼 사람이 스무 장을 먹습니다. 바꿔 끼운
-- 뒤에 옛 장을 지우는 일은 ProfileService.edit 이 합니다. 고르는 자리에서
-- 지우지 않습니다: 판을 저장 안 하고 닫은 사람의 얼굴이 깨집니다.

-- 되메움은 없습니다. 지금까지 아무도 얼굴 사진을 올린 적이 없고, 표식에서
-- 짐작해 채울 수 있는 것도 아닙니다 — 토끼를 고른 사람의 사진은 없습니다.
-- 비어 있는 것이 사실입니다.
