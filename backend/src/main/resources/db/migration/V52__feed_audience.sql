-- 피드 글의 공개 범위.
--
-- 여행기(trip_posts.visibility)에는 V33 부터 있었는데 피드에는 없었습니다.
-- 피드는 「올리는 데 드는 품이 사진 고르기 하나」라서 아무것도 안 받기로 한
-- 것이었는데, 그 대가로 올린 자리가 곧 공개 범위가 되었습니다 — 모임에 올리면
-- 그 모임 사람, 내 피드에 쓰면 나만. 바꾸려면 글을 지우고 다시 써야 했습니다.
--
--   EVERYONE  모두. 번호를 아는 사람이면 봅니다.
--   MATES     내 모임 사람만. 모임에 올린 글이면 그 모임 사람, 내 피드에
--             쓴 글이면 나와 모임을 함께 쓰는 사람입니다.
--   ONLY_ME   나만. 글쓴이 말고는 열 수 없습니다.
--
-- 여행기의 Visibility 를 나눠 쓰지 않습니다. LINK(주소 아는 사람만)는 피드에
-- 뜻이 없고 — 피드에는 남이 뒤지는 목록이 애초에 없어서 "목록에서는 빠지고
-- 주소로는 열린다" 가 할 일이 없습니다 — 거꾸로 「내 모임 사람만」은 여행기에
-- 없습니다. 값 하나를 영영 안 쓰고 값 하나를 새로 붙이면 같은 것을 쓰는 게
-- 아니라 이름만 같은 것이 됩니다(feed/domain/Audience).

-- 기본값을 ONLY_ME 로 둡니다. 모르고 넓게 열리는 쪽이 모르고 좁게 닫히는
-- 쪽보다 되돌리기 어렵습니다 — 이미 남이 본 것은 못 거둡니다. 코드는 늘 값을
-- 넣지만(feed/domain/Post 의 빌더), 어딘가에서 빼먹더라도 새어 나가지 않게
-- DB 쪽에도 같은 기본값을 둡니다.
ALTER TABLE posts ADD COLUMN audience VARCHAR(12) NOT NULL DEFAULT 'ONLY_ME';

-- 이미 올라간 글은 지금 보이는 대로 그대로 보여야 합니다.
--
--   group_id 가 있는 글 → 그 모임 사람이 보고 있었습니다 → MATES
--   group_id 가 없는 글 → 글쓴이만 보고 있었습니다       → ONLY_ME (위 기본값)
--
-- 이 한 줄을 빼면 모임 피드가 통째로 빈 화면이 됩니다. 거꾸로 전부 MATES 로
-- 채우면 혼자 쓰던 글이 모임 사람에게 새어 나갑니다 — 두 갈래를 꼭 갈라야
-- 하는 자리입니다.
UPDATE posts SET audience = 'MATES' WHERE group_id IS NOT NULL;

-- 색인은 안 답니다.
--
-- 목록 질의에 붙는 조건은 audience <> 'ONLY_ME' 하나입니다. 모임 피드를
-- 고르는 일은 idx_posts_group (group_id, created_at DESC) 이 이미 하고, 그렇게
-- 고른 줄 가운데 ONLY_ME 는 드뭅니다 — 모임에 올려 두고 혼자만 보는 글입니다.
-- 거의 아무것도 걸러 내지 않는 조건에 색인을 붙이면 쓰이지도 않으면서 글을
-- 쓸 때마다 값을 치릅니다.
