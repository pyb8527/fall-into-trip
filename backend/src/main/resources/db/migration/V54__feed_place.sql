-- 피드 글이 묶이는 장소.
--
-- 여행에는 V39 부터 묶였습니다(posts.trip_id). 그런데 여행 하나가 닷새에
-- 스무 곳이면 「이 여행 이야기」는 사진이 설 자리를 못 집어 줍니다 — 둘러보기에
-- 내놓을 때 그 사진이 어느 장소 자리에 들어가야 하는지 아무도 모릅니다. 사람이
-- 내놓기 판에서 장소마다 사진을 하나하나 다시 골랐습니다. 이미 그 장소를 보면서
-- 올린 사진인데 말입니다.
--
-- 장소를 받습니다. 받는 쪽은 올릴 때 한 번이고, 그 한 번으로 둘러보기 사본의
-- 장소 자리가 저절로 채워집니다.

-- ------------------------------------------------------------------ 어느 칸
--
-- place_id 하나만 둡니다. day_id 를 같이 두지 않습니다.
--
--   장소는 이미 날에 달려 있습니다(places.day_id → days.id → trips.id). 날을
--   또 적어 두면 같은 사실이 두 군데에 있고, <b>둘은 어긋날 수 있습니다</b> —
--   장소를 끌어서 다른 날로 옮기면 places.day_id 는 따라 바뀌는데 여기 적힌
--   day_id 는 그대로 남습니다. 그러면 사진이 가 본 적 없는 날에 놓이고, 그것을
--   고쳐 줄 자리가 어디에도 없습니다.
--
--   날을 고르는 칸은 화면에 있습니다. 다만 그것은 <b>장소를 좁히는 단계</b>라
--   저장하지 않습니다 — 닷새에 스무 곳이면 장소 칩이 스물인데, 날을 먼저
--   고르면 네댓이 됩니다. 서버가 날이 필요한 자리에서는 장소에서 거슬러
--   올라갑니다(feed/application/FeedService 의 placeOf).
--
-- 여행 번호도 그대로 둡니다(trip_id). 장소에서 거슬러 올라가면 알 수 있으니
-- 지울 수도 있었는데, 장소를 안 고른 글이 대부분이고 그 글들도 여행에는
-- 묶입니다 — 숙소에서 찍은 단체 사진은 장소에 설 자리가 없습니다. 둘 다
-- 보낼 때 어긋나지 못하게 막는 일은 코드가 합니다(placeOf).
ALTER TABLE posts ADD COLUMN place_id VARCHAR(16) REFERENCES places (id) ON DELETE SET NULL;

-- ------------------------------------------------------------------ 지울 때
--
-- 장소가 사라지면 <b>묶임만</b> 끊습니다(SET NULL). 글은 글자와 사진을 그대로
-- 들고 남습니다.
--
-- CASCADE 로 두면 일정에서 장소 한 줄을 빼는 일이 <b>남의 글을 지우는 일</b>이
-- 됩니다. 일정의 장소는 끌어서 옮기고 지우고 다시 넣는 것이 흔한 줄이고, 모임
-- 여행이면 그 일을 하는 사람과 글을 쓴 사람이 다릅니다. "오사카 둘째 날 카페를
-- 딴 데로 바꿨어" 가 누군가의 사진 열 장을 데려가면, 데려간 사람도 잃은 사람도
-- 그 일이 일어난 것을 모릅니다.
--
-- trip_id 와 같은 규칙입니다(V39 — "글은 그 여행이 아니라 그때 있었던 일에
-- 대한 것입니다"). 장소도 그렇습니다 — 사진이 찍힌 것은 그 자리이고, 일정의
-- 줄 하나가 사라지는 것과는 다른 일입니다.

-- ------------------------------------------------------------------ 색인
--
-- 색인은 안 답니다.
--
-- 이 칸으로 거르는 질의가 없습니다. 내놓기 판은 여행으로 한 번 받아 온
-- 글들(idx_posts_trip)을 화면에서 장소별로 묶고, 여행 하나에 붙는 글은 많아야
-- 몇십 편입니다. 장소 하나로 글을 찾는 화면은 없습니다 — 장소를 보는 자리에
-- 서는 것은 그 장소의 「한 줄」이고 피드가 아닙니다.
--
-- 외래키 때문에 다는 길도 있습니다. 장소를 지울 때 PostgreSQL 이 이 칸을
-- 훑어야 하니까요. 그런데 장소를 지우는 일은 사람이 한 번 누르는 일이고,
-- posts 는 한 사람이 500편으로 묶여 있습니다 — 그 한 번을 위해 글을 쓸 때마다
-- 색인 값을 치를 이유가 없습니다. V52 가 audience 에 색인을 안 단 것과 같은
-- 셈입니다.

-- 되메움은 없습니다. 지금까지 올라간 글에는 장소가 없었고, 짐작해 채우면
-- 틀린 자리에 사진이 섭니다 — 올린 때로 날을 꼽을 수는 있어도 그날 어느
-- 장소였는지는 아무 데도 적혀 있지 않습니다. 비어 있는 것이 사실입니다.
